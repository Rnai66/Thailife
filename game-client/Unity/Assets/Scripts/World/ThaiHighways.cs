    // The town a place (Locations id) is in; the home province's for the village, ตำบล, town and beach
    public static string TownOf(string placeId)
    {
        if (placeId != null && PlaceTown.TryGetValue(placeId, out var town)) return town;
        var home = AddressClient.Last != null ? AddressClient.Last.province : null;
        return Index(home) >= 0 ? home : Provinces.Default;
    }

    public static string Short(string town) => town == "กรุงเทพมหานคร" ? "กรุงเทพฯ" : town == "พระนครศรีอยุธยา" ? "อยุธยา" : town;

    private static int Index(string town)
    {
        if (string.IsNullOrEmpty(town)) return -1;
        for (int i = 0; i < Towns.Length; i++) if (Towns[i].name == town) return i;
        return -1;
    }

    public static Vector2 LatLon(string town)
    {
        int i = Index(town);
        return i < 0 ? Vector2.zero : new Vector2(Towns[i].lat, Towns[i].lon);
    }

    private static float Km(int a, int b)
    {
        float dlat = Towns[a].lat - Towns[b].lat;
        float dlon = (Towns[a].lon - Towns[b].lon) * Mathf.Cos((Towns[a].lat + Towns[b].lat) * 0.5f * Mathf.Deg2Rad);
        return 111.2f * Mathf.Sqrt(dlat * dlat + dlon * dlon) * RoadFactor;
    }

    // Every road as two map points (lat, lon), for drawing the country
    public static IEnumerable<(Vector2 a, Vector2 b, string route)> AllRoads()
    {
        foreach (var r in Roads) yield return (LatLon(r.a), LatLon(r.b), r.route);
    }

    // The shortest way along the highways from one town to another (Dijkstra), or an empty list
    public static List<Leg> Route(string from, string to)
    {
        var legs = new List<Leg>();
        int s = Index(from), t = Index(to), n = Towns.Length;
        if (s < 0 || t < 0 || s == t) return legs;
        var cost = new float[n];
        var prev = new int[n];
        var via = new int[n];
        var done = new bool[n];
        for (int i = 0; i < n; i++) { cost[i] = float.MaxValue; prev[i] = -1; }
        cost[s] = 0f;
        for (int step = 0; step < n; step++)
        {
            int u = -1;
            for (int i = 0; i < n; i++) if (!done[i] && cost[i] < float.MaxValue && (u < 0 || cost[i] < cost[u])) u = i;
            if (u < 0 || u == t) break;
            done[u] = true;
            for (int k = 0; k < Roads.Length; k++)
            {
                int a = Index(Roads[k].a), b = Index(Roads[k].b);
                int v = a == u ? b : b == u ? a : -1;
                if (v < 0 || done[v]) continue;
                float c = cost[u] + Km(u, v);
                if (c < cost[v]) { cost[v] = c; prev[v] = u; via[v] = k; }
            }
        }
        if (prev[t] < 0) return legs;
        for (int v = t; v != s; v = prev[v])
            legs.Insert(0, new Leg { from = Towns[prev[v]].name, to = Towns[v].name, highway = Roads[via[v]].route, km = Km(prev[v], v) });
        return legs;
    }
